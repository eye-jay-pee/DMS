use super::*;
impl Dms {
    pub fn make_negative(&mut self) {}
    pub fn make_positive(&mut self) {}
    pub fn flip_sign(&mut self) {
        if self.is_negative() {
            self.make_positive();
        } else {
            make_negative();
        }
    }
}
